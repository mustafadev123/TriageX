import '@testing-library/jest-dom/vitest'
import { cleanup } from '@testing-library/react'
import { afterEach } from 'vitest'

afterEach(() => cleanup())

// jsdom lacks these browser APIs. Charts and the map measure themselves with
// ResizeObserver; in tests they render without size (chart data is unit-tested in lib/).
class NoopResizeObserver {
  observe() {}
  unobserve() {}
  disconnect() {}
}
globalThis.ResizeObserver ??= NoopResizeObserver as unknown as typeof ResizeObserver

// No live socket in tests; the dashboard must work without one.
class NoopWebSocket {
  onopen: (() => void) | null = null
  onmessage: ((e: MessageEvent) => void) | null = null
  onclose: (() => void) | null = null
  close() {}
}
globalThis.WebSocket = NoopWebSocket as unknown as typeof WebSocket
