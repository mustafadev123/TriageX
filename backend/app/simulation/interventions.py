"""Human-approved TriageX interventions (Track B only).

An intervention is an input to the simulation, never something the engine decides on
its own. Proposals are generated by the engine; interventions exist only once a human
approves them (and, for staffing, once staff confirm).
"""

from __future__ import annotations

from dataclasses import dataclass

from app.simulation.hospitals import Network
from app.simulation.models import Proposal

STAFF_LEAD_TICKS = 3  # 45 simulated minutes between request and staff on the floor
STAFF_SHIFT_TICKS = 16  # 4-hour surge shift
LEVEL_LOAD_LEAD_TICKS = 1  # 15 minutes to notify EMS dispatch
LEVEL_LOAD_DURATION_TICKS = 16
MAX_CONFIRMED_STAFF = 20


@dataclass(frozen=True, slots=True)
class StaffingIntervention:
    """Confirmed extra staff for one hospital. Effective only after the lead time."""

    id: str
    hospital_id: str
    approved_tick: int  # when the operator approved the outreach request
    confirmed_staff: int  # number of staff who replied IN
    lead_ticks: int = STAFF_LEAD_TICKS
    duration_ticks: int = STAFF_SHIFT_TICKS

    @property
    def effective_tick(self) -> int:
        return self.approved_tick + self.lead_ticks

    @property
    def end_tick(self) -> int:  # exclusive
        return self.effective_tick + self.duration_ticks

    def active(self, tick: int) -> bool:
        return self.confirmed_staff > 0 and self.effective_tick <= tick < self.end_tick


@dataclass(frozen=True, slots=True)
class LevelLoadingIntervention:
    """Redirect lower-acuity inbound ambulances away from a pressured hospital."""

    id: str
    source_hospital_id: str
    approved_tick: int
    max_redirects_per_tick: int = 2
    min_acuity: int = 3  # only the least urgent patients are redirected
    receiver_forecast_limit_pct: float = 80.0
    lead_ticks: int = LEVEL_LOAD_LEAD_TICKS
    duration_ticks: int = LEVEL_LOAD_DURATION_TICKS

    @property
    def hospital_id(self) -> str:
        return self.source_hospital_id

    @property
    def effective_tick(self) -> int:
        return self.approved_tick + self.lead_ticks

    @property
    def end_tick(self) -> int:
        return self.effective_tick + self.duration_ticks

    def active(self, tick: int) -> bool:
        return self.effective_tick <= tick < self.end_tick


Intervention = StaffingIntervention | LevelLoadingIntervention


def validate_interventions(
    interventions: tuple[Intervention, ...], network: Network, horizon_ticks: int
) -> None:
    ids = [iv.id for iv in interventions]
    if len(set(ids)) != len(ids):
        raise ValueError("Intervention ids must be unique")
    for iv in interventions:
        if iv.hospital_id not in network.index:
            raise ValueError(f"Intervention {iv.id}: unknown hospital '{iv.hospital_id}'")
        if not (0 <= iv.approved_tick < horizon_ticks):
            raise ValueError(f"Intervention {iv.id}: approved_tick outside the horizon")
        if iv.lead_ticks < 0 or iv.duration_ticks <= 0:
            raise ValueError(f"Intervention {iv.id}: invalid lead or duration")
        if isinstance(iv, StaffingIntervention):
            if not (0 <= iv.confirmed_staff <= MAX_CONFIRMED_STAFF):
                raise ValueError(f"Intervention {iv.id}: confirmed_staff out of range")
        elif isinstance(iv, LevelLoadingIntervention):
            if iv.max_redirects_per_tick < 0 or iv.min_acuity not in (1, 2, 3):
                raise ValueError(f"Intervention {iv.id}: invalid level-loading limits")
        else:
            raise TypeError(f"Unsupported intervention type: {type(iv).__name__}")


def interventions_from_proposal(
    proposal: Proposal,
    approved_tick: int,
    confirmed_staff: int,
    include_level_loading: bool = True,
) -> tuple[Intervention, ...]:
    """Build the interventions a human approval of `proposal` would create."""
    if approved_tick < proposal.tick:
        raise ValueError("A proposal cannot be approved before it was made")
    result: list[Intervention] = [
        StaffingIntervention(
            id=f"{proposal.id}:staffing",
            hospital_id=proposal.hospital_id,
            approved_tick=approved_tick,
            confirmed_staff=confirmed_staff,
        )
    ]
    if include_level_loading:
        result.append(
            LevelLoadingIntervention(
                id=f"{proposal.id}:level_loading",
                source_hospital_id=proposal.hospital_id,
                approved_tick=approved_tick,
            )
        )
    return tuple(result)
